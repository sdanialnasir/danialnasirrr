#!/usr/bin/env python3
"""Regenerate src/assets/art-data.js from the image files listed in src/assets/asset-manifest.json.
Edit or replace any image in src/assets/images/, then run this (build.py runs it automatically)."""
import re, base64, json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); SRC = os.path.join(ROOT, 'src')
def mp3_seconds(b):
    """Length of a constant-bitrate MP3 from its first frame header (the clips are made CBR by tools/import_voices.py); 0 if unreadable."""
    i = 0
    if b[:3] == b'ID3' and len(b) > 10: i = 10 + ((b[6] & 0x7f) << 21 | (b[7] & 0x7f) << 14 | (b[8] & 0x7f) << 7 | (b[9] & 0x7f))
    while i + 4 < len(b):
        if b[i] == 0xFF and (b[i + 1] & 0xE0) == 0xE0:
            ver = (b[i + 1] >> 3) & 3; br = (b[i + 2] >> 4) & 15
            if ver != 1 and 0 < br < 15:
                kbps = ([0, 32, 40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320] if ver == 3 else [0, 8, 16, 24, 32, 40, 48, 56, 64, 80, 96, 112, 128, 144, 160])[br]
                return round((len(b) - i) * 8 / (kbps * 1000), 3)
        i += 1
    return 0

def uri(rel):
    p = os.path.join(SRC, rel); ext = os.path.splitext(p)[1].lower(); mime = 'image/png' if ext == '.png' else 'image/jpeg'
    return f'data:{mime};base64,' + base64.b64encode(open(p, 'rb').read()).decode()
def webp(rel, q=90):
    # sheet sprites ship as WebP (same look, about a third of the PNG size); `exact` keeps the colour under transparent pixels so
    # filtered edges don't pick up dark fringes. Falls back to the PNG when Pillow can't write WebP.
    p = os.path.join(SRC, rel)
    try:
        from PIL import Image
        import io
        im = Image.open(p); im = im.convert('RGBA') if im.mode not in ('RGB', 'RGBA') else im
        b = io.BytesIO(); im.save(b, 'WEBP', quality=q, method=6, exact=True, alpha_quality=100)
        if b.tell() < os.path.getsize(p): return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()
    except Exception as e:
        print('webp skipped for', rel, e)
    return uri(rel)
def main():
    man = json.load(open(os.path.join(SRC, 'assets', 'asset-manifest.json')))
    sheet = {k: [webp(v['file']), v['w'], v['h']] for k, v in man['SHEET_SPR'].items()}
    # (ART_SRC — the old art set — is no longer used by the game, so it isn't embedded)
    data = {'SHEET_SPR': sheet, 'PHOTO_BG_URI': webp(man['PHOTO_BG_URI'], 88)}
    # optional per-world paintings: src/assets/images/background/bg_photo_w2.jpg (Coral Caves) / bg_photo_w3.jpg (The Deep), same 2560x1435 framing
    for w in (2, 3):
        for ext in ('jpg', 'png'):
            rel = f'assets/images/background/bg_photo_w{w}.{ext}'
            if os.path.exists(os.path.join(SRC, rel)): data[f'PHOTO_BG_W{w}'] = uri(rel); break
    # UI elements (compressed WebPs made by tools/compress_ui.py) -> AQ_DATA.UI, exposed to the CSS as --ui-<key>
    ui_dir = os.path.join(SRC, 'assets', 'images', 'ui')
    if os.path.isdir(ui_dir):
        data['UI'] = {os.path.splitext(f)[0]: 'data:image/webp;base64,' + base64.b64encode(open(os.path.join(ui_dir, f), 'rb').read()).decode()
                      for f in sorted(os.listdir(ui_dir)) if f.endswith('.webp')}
    # textures cut from the owner's reference art (tools/make_ref_textures.py) -> AQ_DATA.TEX
    tex_dir = os.path.join(SRC, 'assets', 'images', 'tex')
    if os.path.isdir(tex_dir):
        data['TEX'] = {os.path.splitext(f)[0]: 'data:image/webp;base64,' + base64.b64encode(open(os.path.join(tex_dir, f), 'rb').read()).decode()
                       for f in sorted(os.listdir(tex_dir)) if f.endswith('.webp')}
    # optional voice-over clips for the intro: src/assets/vo/<line id>.mp3 (e.g. vo1.mp3 ... vo7.mp3) -> AQ_DATA.VO
    vo_dir = os.path.join(SRC, 'assets', 'vo')
    if os.path.isdir(vo_dir):
        # the intro / tutorial / diver clips travel inside the page; the story script (~23 min of speech) is too big for one file under
        # 16 MB, so it ships as three companion packs, one per world: src/assets/voice-<w>.js (copied to dist/assets/), loaded in the background
        packs = {1: ({}, {}), 2: ({}, {}), 3: ({}, {})}; data['VO'] = {}; data['VOD'] = {}
        for f in sorted(os.listdir(vo_dir)):
            if not f.lower().endswith('.mp3'): continue
            i, b = os.path.splitext(f)[0], open(os.path.join(vo_dir, f), 'rb').read(); uri = 'data:audio/mpeg;base64,' + base64.b64encode(b).decode()
            m = re.match(r'^(?:s|l|m)(\d+)(?:_|$)', i); w = (1 if i.startswith('k_') else min(3, (int(m.group(1)) - 1) // 10 + 1) if m else 0)
            if w: packs[w][0][i] = uri; packs[w][1][i] = mp3_seconds(b)
            else: data['VO'][i] = uri; data['VOD'][i] = mp3_seconds(b)
        for w, (vo, vd) in packs.items():
            out = os.path.join(SRC, 'assets', f'voice-{w}.js')
            if vo: open(out, 'w').write('/* generated by tools/build_assets.py: story voice pack, world %d */\nwindow.AQ_VOICE && AQ_VOICE(%s);\n' % (w, json.dumps({'VO': vo, 'VOD': vd}, separators=(',', ':'))))
            elif os.path.exists(out): os.remove(out)
            if vo: print(f'voice pack {w}: {len(vo)} clips, {os.path.getsize(out) // 1024} KB')
    # optional real sound effects: src/assets/sfx/<name>.mp3 (variants <name>_2.mp3 ...) -> AQ_DATA.SFX (they replace the synthesized sound)
    # optional ambience loop: src/assets/music/ambience.mp3 -> AQ_DATA.MUSIC (replaces the synth pad). See docs/sound-list.md.
    for key, sub in (('SFX', 'sfx'), ('MUSIC', 'music')):
        d = os.path.join(SRC, 'assets', sub)
        if os.path.isdir(d):
            data[key] = {os.path.splitext(f)[0]: 'data:audio/mpeg;base64,' + base64.b64encode(open(os.path.join(d, f), 'rb').read()).decode()
                         for f in sorted(os.listdir(d)) if f.lower().endswith('.mp3')}
    out = os.path.join(SRC, 'assets', 'art-data.js')
    open(out, 'w').write('// GENERATED by tools/build_assets.py from src/assets/images/* — do not edit by hand.\nwindow.AQ_DATA = ' + json.dumps(data) + ';\n')
    print('wrote', out, os.path.getsize(out) // 1024, 'KB')
if __name__ == '__main__': main()
