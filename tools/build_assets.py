#!/usr/bin/env python3
"""Regenerate src/assets/art-data.js from the image files listed in src/assets/asset-manifest.json.
Edit or replace any image in src/assets/images/, then run this (build.py runs it automatically)."""
import base64, json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); SRC = os.path.join(ROOT, 'src')
def uri(rel):
    p = os.path.join(SRC, rel); ext = os.path.splitext(p)[1].lower(); mime = 'image/png' if ext == '.png' else 'image/jpeg'
    return f'data:{mime};base64,' + base64.b64encode(open(p, 'rb').read()).decode()
def main():
    man = json.load(open(os.path.join(SRC, 'assets', 'asset-manifest.json')))
    sheet = {k: [uri(v['file']), v['w'], v['h']] for k, v in man['SHEET_SPR'].items()}
    art = {k: ([uri(x) for x in v] if isinstance(v, list) else uri(v)) for k, v in man['ART_SRC'].items()}
    data = {'SHEET_SPR': sheet, 'ART_SRC': art, 'PHOTO_BG_URI': uri(man['PHOTO_BG_URI'])}
    out = os.path.join(SRC, 'assets', 'art-data.js')
    open(out, 'w').write('// GENERATED by tools/build_assets.py from src/assets/images/* — do not edit by hand.\nwindow.AQ_DATA = ' + json.dumps(data) + ';\n')
    print('wrote', out, os.path.getsize(out) // 1024, 'KB')
if __name__ == '__main__': main()
