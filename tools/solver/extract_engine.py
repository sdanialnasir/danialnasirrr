#!/usr/bin/env python3
"""Extract the pure game engine + level data from src/game.js for the Node solver tools."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); game = open(os.path.join(ROOT, 'src', 'game.js')).read()
here = os.path.dirname(os.path.abspath(__file__))
eng = game[game.index('const T = {'):game.index('const LEVELS = [')]
open(os.path.join(here, 'engine.js'), 'w').write('// GENERATED by extract_engine.py — do not edit\n' + eng + '\nmodule.exports = { Engine, T, MONSTERS };\n')
block = game[game.index('const LEVELS = ['):game.index('\n];', game.index('const LEVELS = ['))]
levels = []
for m in re.finditer(r'\{ name: "([^"]+)", time: (\d+)(.*?)map: \[(.*?)\]\}', block, re.S):
    levels.append({'name': m.group(1), 'time': int(m.group(2)), 'map': re.findall(r"'([^']*)'", m.group(4))})
json.dump(levels, open(os.path.join(here, 'levels.json'), 'w')); print('engine.js + levels.json written,', len(levels), 'levels')
